export function findIconItem(name: string): IconCatalogItem | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  return ICON_CATALOG.find((item) => item.name.toLowerCase() === clean);
}

export function getIconLabel(name: string): string {
  const found = findIconItem(name);
  if (found) return found.label;
  return name;
}
